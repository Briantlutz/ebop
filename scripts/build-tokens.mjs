// Generates src/app/tokens.css from design/ebop-design-tokens.json.
// The JSON file is the single source of truth for color, type, spacing and radius.
// Runs automatically before `npm run dev` and `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(
  readFileSync(join(root, "design/ebop-design-tokens.json"), "utf8"),
);

const colors = tokens.color.tokens;
const colorVars = (theme) =>
  colors.map((t) => `  --${t.name}: ${t.value[theme]};`).join("\n");

const spacing = tokens.spacing.tokens
  .map((t) => `  --${t.name}: ${t.value};`)
  .join("\n");
const radius = tokens.radius.tokens
  .map((t) => `  --${t.name}: ${t.value};`)
  .join("\n");

const familyVar = (key) => (key === "display" ? "var(--font-display)" : "var(--font-sans)");
const typeRules = tokens.type.groups
  .flatMap((g) =>
    g.styles.map(
      (s) => `.type-${s.name} {
  font-family: ${familyVar(g.family)};
  font-size: ${s.fontSize};
  line-height: ${s.lineHeight};
  font-weight: ${s.fontWeight};
}`,
    ),
  )
  .join("\n");

const css = `/* GENERATED by scripts/build-tokens.mjs from design/ebop-design-tokens.json. Do not edit by hand. */

:root {
  color-scheme: light;
${colorVars("light")}
${spacing}
${radius}
}

/* Dark ("Night Shift") follows the device setting unless the user picked light. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorVars("dark").replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${colorVars("dark")}
}

${typeRules}
`;

writeFileSync(join(root, "src/app/tokens.css"), css);
console.log("tokens.css written");
